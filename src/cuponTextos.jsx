const CLAVE_IDIOMA = 'mittoz_idioma';

export function idiomaInicial() {
  const q = new URLSearchParams(window.location.search).get('lang');
  if (q && TEXTOS[q]) return q;
  try {
    const g = localStorage.getItem(CLAVE_IDIOMA);
    if (g && TEXTOS[g]) return g;
  } catch { /* sin almacenamiento */ }
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return TEXTOS[nav] ? nav : (nav === 'es' ? 'es' : 'en');
}

export function guardarIdioma(id) {
  try { localStorage.setItem(CLAVE_IDIOMA, id); } catch { /* sin almacenamiento */ }
}
